#!/usr/bin/env python3
"""G0-B03: deterministic *within each CI run* FLAC seek fixture set.

Requires the ffmpeg and metaflac CLI binaries on the fixture-preparation runner.
The generated bytes are uploaded once and shared unchanged by both comparison
jobs. FFmpeg CLI version is recorded; the APIs under test are in the iOS builds.
"""
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys

SAMPLE_RATE = 44_100
CASES = (
    ("025", "0.25", 11_025),
    ("050", "0.50", 22_050),
    ("200", "2.00", 88_200),
    ("1000", "10.00", 441_000),
)


def run(*args: str) -> str:
    result = subprocess.run(args, check=True, text=True, capture_output=True)
    return result.stdout.strip()


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("Usage: g0_generate_flac_matrix.py OUTPUT_DIRECTORY")
    for command in ("ffmpeg", "metaflac"):
        if not shutil.which(command):
            raise SystemExit(f"Missing required fixture generator: {command}")

    out = pathlib.Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    manifest = {
        "generator": {
            "ffmpeg": run("ffmpeg", "-version").splitlines()[0],
            "metaflac": run("metaflac", "--version").splitlines()[0],
        },
        "sample_rate": SAMPLE_RATE,
        "channels": 2,
        "bit_depth": 16,
        "files": [],
    }

    for tag, duration, expected_samples in CASES:
        plain = out / f"seek_{tag}_no_table.flac"
        table = out / f"seek_{tag}_table.flac"

        run(
            "ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi",
            "-i", f"sine=frequency=440:sample_rate={SAMPLE_RATE}:duration={duration}",
            "-ac", "2", "-ar", str(SAMPLE_RATE),
            "-c:a", "flac", "-sample_fmt", "s16", "-compression_level", "5",
            str(plain),
        )
        assert int(run("metaflac", "--show-total-samples", str(plain))) == expected_samples
        assert not run("metaflac", "--list", "--block-type=SEEKTABLE", str(plain))

        shutil.copyfile(plain, table)
        run(
            "metaflac",
            "--add-seekpoint=0",
            f"--add-seekpoint={expected_samples // 4}",
            f"--add-seekpoint={expected_samples // 2}",
            f"--add-seekpoint={(expected_samples * 9) // 10}",
            str(table),
        )
        listing = run("metaflac", "--list", "--block-type=SEEKTABLE", str(table))
        assert "type: 3 (SEEKTABLE)" in listing
        assert "sample_number=0" in listing
        assert int(run("metaflac", "--show-total-samples", str(table))) == expected_samples

        for file, has_table in ((plain, False), (table, True)):
            raw = file.read_bytes()
            assert raw.startswith(b"fLaC")
            manifest["files"].append({
                "file": file.name,
                "duration_s": float(duration),
                "total_samples": expected_samples,
                "seektable": has_table,
                "bytes": len(raw),
                "sha256": hashlib.sha256(raw).hexdigest(),
            })

    (out / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(manifest, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
